def _norm(s):
    return (s or "").strip()


def _contains_token(name_lower: str, tok: str) -> bool:
    """
    Проверка "токенов" в имени файла/пути.
    Чтобы 'lg' не матчило 'flag' и т.п., учитываем разделители.
    """
    return re.search(
        rf'(^|[\\/_.\-]){re.escape(tok)}($|[\\/_.\-])',
        name_lower
    ) is not None


def normalize_city(s: str) -> str:
    s0 = (s or "").strip().lower().replace("ё", "е")
    if s0 in CITY_SYNONYMS:
        return CITY_SYNONYMS[s0]
    for c in TOP_CITIES:
        if s0 == c.lower().replace("ё", "е"):
            return c
    return (s or "").strip()


def generate_addresses(cities, per_city=None, default_per_city=1):
    """
    Генерирует адреса вида 'Город, ул. ..., д. NN'.
    per_city = {"Москва": 3, "Казань": 2} задаёт сколько точек для города,
    иначе default_per_city.
    """
    result = []
    used = set()
    for city in cities:
        n = per_city.get(city, default_per_city) if per_city else default_per_city
        n = max(1, min(30, n))
        for _ in range(n):
            for _try in range(300):
                street = random.choice(STREETS)
                house = random.randint(1, 200)
                addr = f"{city}, {street}, д. {house}"
                if addr not in used:
                    used.add(addr)
                    result.append(addr)
                    break
    return result


def ui_select_cities():
    """
    Диалог выбора городов + генерация адресов.
    1) Авто-топ N городов
    2) Ручной ввод списка городов
    Затем опционально уточняем: "Москва=3, Казань=2" => кол-во адресов на город.
    """
    print("\n=== ВЫБОР ГОРОДОВ ===")
    print("1) Топ (Enter=5)  2) Ручной")
    mode = input("Выберите (1/2, Enter=1): ").strip() or "1"

    if mode == "2":
        raw = input("Города через запятую или столбиком: ").strip()
        parts = [p.strip() for p in re.split(r"[\s,;]+", raw) if p.strip()]
        cities = [normalize_city(p) for p in parts]
    else:
        try:
            n = int(input("Сколько городов из топа? (Enter=5): ").strip() or "5")
        except Exception:
            n = 5
        n = max(1, min(len(TOP_CITIES), n))
        cities = TOP_CITIES[:n]

    raw_more = input(
        "Расширить адресами? (формат Москва=3, Казань=2; Enter — нет): "
    ).strip()

    if raw_more:
        want = {}
        for part in re.split(r"[;\s,]+", raw_more):
            if "=" in part:
                k, v = part.split("=", 1)
                try:
                    want[normalize_city(k)] = int(v.strip())
                except Exception:
                    pass
        return generate_addresses(cities, want, default_per_city=1)

    return generate_addresses(cities, None, default_per_city=1)


def translit_rus_to_lat(text: str) -> str:
    """
    Для ID и префиксов объявлений. Убираем пробелы и кириллицу.
    """
    table = {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
        "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
        "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
        "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
        "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
        " ": "", "-": ""
    }
    out = []
    for c in text:
        lower = c.lower()
        if lower in table:
            out.append(table[lower])
        else:
            out.append(lower)
    return "".join(out)


def _detect_sep_csv(path: str) -> str:
    """
    Определяем ; или , в CSV
    """
    for sep in (';', ','):
        try:
            df = pd.read_csv(path, sep=sep, nrows=2, dtype=str, keep_default_na=False)
            if len(df.columns) >= 3:
                return sep
        except Exception:
            pass
    return ','


def join_photo_urls(urls):
    """
    Авито требует ссылки через |
    """
    clean = []
    seen = set()
    for u in (urls or []):
        if not u:
            continue
        s = str(u).strip()
        if s and s not in seen:
            clean.append(s)
            seen.add(s)
    return PHOTO_URLS_DELIM.join(clean)


def normalize_for_uniqueness(s: str) -> str:
    s = s.strip().lower()
    s = re.sub(r"\s+", " ", s)
    return s


def generate_unique(pair_generator, seen_set: set, max_tries: int = 60):
    """
    Гарантия, что одна и та же модель не выдаёт два одинаковых объявления:
    мы храним нормализованный заголовок и описание без html,
    и если совпало — перегенерируем.
    """
    last = None
    for _ in range(max_tries):
        title, desc = pair_generator()
        last = (title, desc)
        nt = normalize_for_uniqueness(title)
        nd = normalize_for_uniqueness(re.sub(r"<[^>]+>", "", desc))
        if nt not in seen_set and nd not in seen_set:
            seen_set.add(nt)
            seen_set.add(nd)
            return title, desc
    return last


def format_for_avito(html_text: str) -> str:
    """
    Авито нормально ест <p> и <br>.
    Структурируем и нормализуем.
    """
    if not html_text:
        return ""
    html_text = html_text.replace("&nbsp;", " ")
    html_text = html_text.strip()
    # убедимся что обёрнуто в параграфы
    parts = []
    for block in re.split(r"</p>\s*<p>", html_text):
        b = block.strip()
        if not b:
            continue
        if not b.startswith("<p>"):
            b = "<p>" + b
        if not b.endswith("</p>"):
            b = b + "</p>"
        parts.append(b)
    final = "".join(parts)
    if not final:
        final = "<p>" + html_text + "</p>"
    return final


