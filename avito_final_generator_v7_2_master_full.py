def prioritize_specs(spec_list: list, top_n: int = 2) -> list:
    """
    Берём список строк с характеристиками.
    Переставляем так, чтобы первые 1-2 "самые важные"
    (мощность, объём, дымоход, габариты и т.п.) шли сверху.
    Остальное перемешиваем, но без потери смысла.
    """
    PRIORITY_HINTS = [
        "мощн", "объем", "объём", "рассчит", "обогрев", "обогревает",
        "дымохо", "вентилятор", "теплопроизводительность",
        "производительность", "габарит", "камера", "объём камеры"
    ]
    if not spec_list:
        return []

    pri = []
    rest = []
    for s in spec_list:
        low = s.lower()
        if any(h in low for h in PRIORITY_HINTS) and len(pri) < top_n:
            pri.append(s)
        else:
            rest.append(s)

    random.shuffle(rest)

    # убрать дубли
    out = []
    used = set()
    for s in pri + rest:
        if s not in used:
            out.append(s)
            used.add(s)
    return out


def assemble_specs_block(model_data: dict) -> str:
    """
    Возвращает HTML-строку со списком характеристик "<br>· ..."
    """
    specs_list = model_data.get("specs", [])
    ordered = prioritize_specs(specs_list, top_n=2)
    return "<br>".join("· " + s for s in ordered)


def assemble_kit_block(model_data: dict) -> str:
    """
    Берём набор комплектующих (kit_items), тасуем,
    упаковываем в одну красивую строку через запятую,
    и подставляем в рандомный текстовый шаблон из KIT_PHRASES.
    """
    items = list(model_data.get("kit_items", []))
    if not items:
        return ""
    random.shuffle(items)
    # Склеим с запятыми и "и" перед последним при желании
    if len(items) > 2:
        items_str = ", ".join(items[:-1]) + ", " + items[-1]
    elif len(items) == 2:
        items_str = items[0] + ", " + items[1]
    else:
        items_str = items[0]
    phr = random.choice(KIT_PHRASES)
    return phr.format(items=items_str)


