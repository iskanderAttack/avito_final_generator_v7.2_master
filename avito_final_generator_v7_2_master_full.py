def extract_power_value_kw(power_text: str) -> float:
    """
    Из строки "70 кВт" достаём число 70 как float.
    Если не нашли — возвращаем 0.
    """
    m = re.search(r"(\d+(?:[.,]\d+)?)", str(power_text))
    if not m:
        return 0.0
    return float(m.group(1).replace(",", "."))


def build_family_power_order():
    """
    Для апселла внутри линейки:
    находим для каждой fam список моделей, сортируем по мощности.
    """
    fam_map = {}
    for mid, data in MODELS.items():
        fam = data["fam"]
        pval = extract_power_value_kw(data.get("power", ""))
        fam_map.setdefault(fam, []).append((pval, mid))
    # сортируем по мощности
    for fam in fam_map:
        fam_map[fam].sort(key=lambda x: x[0])
        fam_map[fam] = [mid for (_, mid) in fam_map[fam]]
    return fam_map


FAMILY_ORDER = build_family_power_order()


def suggest_upgrade_model(current_mid: str) -> str:
    """
    Возвращает модель следующей мощности в той же линейке,
    чтобы использовать в апселле.
    Если нет более мощной - просто вернём текущую (без увеличения).
    """
    cur = MODELS[current_mid]
    fam = cur["fam"]
    fam_list = FAMILY_ORDER.get(fam, [])
    if current_mid not in fam_list:
        return MODELS[current_mid]["display_name"]
    idx = fam_list.index(current_mid)
    # если есть более крупная модель - даём её
    if idx < len(fam_list) - 1:
        return MODELS[fam_list[idx + 1]]["display_name"]
    # иначе возвращаем текущую
    return MODELS[current_mid]["display_name"]


def suggest_cross_lineup(current_mid: str) -> str:
    fam = MODELS[current_mid]["fam"]
    return CROSS_LINEUP.get(fam, "")


