def generate_smart_prefixes(selected_model_ids):
    """
    Генерируем префиксы объявлений, чтобы потом к ним приписывать счётчик.
    Пример: MUS300_2510_001
    """
    now = datetime.now()
    year = str(now.year)[-2:]  # последние 2 цифры года
    month = f"{now.month:02d}"

    base_suffix = f"{year}{month}_"
    prefixes = {}
    for mid in selected_model_ids:
        disp = MODELS[mid]["display_name"]
        # берём первое слово как линейку (Муссон / Циклон / ...)
        parts = disp.split()
        base_name = parts[0] if parts else disp
        # берём число мощности из названия, если есть
        num = re.findall(r"\d+", disp)
        num_part = num[0] if num else ""
        name_lat = translit_rus_to_lat(base_name)[:3].upper()
        prefixes[mid] = f"{name_lat}{num_part}{base_suffix}"
    return prefixes


