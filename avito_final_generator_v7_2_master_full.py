def load_photo_database():
    """
    Читает photo_links_filled_AVITO.csv
    и складывает в словарь:
    PHOTO_DB[folder_key] = [ {file, url, full}, ... ]
    где folder_key может быть и верхний уровень (musson),
    и вложенный (musson-600), и хвост пути.
    """
    photos = {}

    if not os.path.exists(PHOTO_CSV):
        print(f"⚠️ Не найден CSV с фото: {PHOTO_CSV}")
        return photos

    try:
        sep = _detect_sep_csv(PHOTO_CSV)
        df = pd.read_csv(PHOTO_CSV, sep=sep, dtype=str, keep_default_na=False)
        lower_cols = {c.lower(): c for c in df.columns}
        mp_col = lower_cols.get("model_path") or lower_cols.get("path")
        fn_col = lower_cols.get("filename")
        url_col = lower_cols.get("url")
        if not (mp_col and fn_col and url_col):
            raise ValueError(
                "CSV должен содержать колонки: model_path/path, filename, url"
            )

        for _, row in df.iterrows():
            model_path = _norm(row[mp_col]).replace("\\", "/")
            filename = _norm(row[fn_col])
            url = _norm(row[url_col])
            if not filename or not url:
                continue
            full = f"{model_path}/{filename}".lower()
            parts = [p for p in model_path.split("/") if p]
            top = parts[0].lower() if parts else ""
            tail = parts[-1].lower() if parts else ""

            rec = {
                "file": filename,
                "url": url,
                "full": full,
            }

            if tail:
                photos.setdefault(tail, []).append(rec)
            if top:
                photos.setdefault(top, []).append(rec)

            # Специально для линейки триумф+циклон (общие фото)
            if top == "triumf+ciklon" or tail == "triumf+ciklon":
                photos.setdefault("triumf+ciklon", []).append(rec)

    except Exception as e:
        print(f"⚠️ Ошибка загрузки базы фото: {e}")

    # перемешаем чтобы не всегда шли одинаково
    for k in photos:
        random.shuffle(photos[k])

    total = sum(len(v) for v in photos.values())
    print(f"📷 Фото-база: {total} записей")
    return photos


PHOTO_DB = load_photo_database()


def _pool_for_model(photo_key: str, fam: str):
    """
    Собираем общий пул кандидатов для конкретной модели:
    - сначала конкретный photo_key (например musson-600)
    - затем семейство (musson)
    - для triumf и ciklon добавим общую папку triumf+ciklon
    """
    pk = (photo_key or "").lower()
    family = (fam or "").lower()

    pool = PHOTO_DB.get(pk, []).copy()

    if len(pool) < 2:
        pool.extend(PHOTO_DB.get(family, []))

    if family in ("triumf", "ciklon") and "triumf+ciklon" in PHOTO_DB:
        pool.extend(PHOTO_DB["triumf+ciklon"])

    # Убираем возможные дубликаты по url
    uniq = {}
    for r in pool:
        uniq[r["url"]] = r
    return list(uniq.values())


def _split_by_prefixes(pool):
    """
    Режем пул на группы по наличию ROOM и ANGLE префиксов.
    both: (room, angle, rec)
    only_room: (room, rec)
    only_angle: (angle, rec)
    none: rec
    """
    both = []
    only_room = []
    only_angle = []
    none = []

    for rec in pool:
        name = rec["full"]
        has_room = None
        for r in ROOMS:
            if _contains_token(name, r):
                has_room = r
                break

        has_angle = None
        for a in ANGLES:
            if _contains_token(name, a):
                has_angle = a
                break

        if has_room and has_angle:
            both.append((has_room, has_angle, rec))
        elif has_room and not has_angle:
            only_room.append((has_room, rec))
        elif (not has_room) and has_angle:
            only_angle.append((has_angle, rec))
        else:
            none.append(rec)

    return both, only_room, only_angle, none


def _weighted_room_subset(rnd: random.Random) -> list:
    """
    Выбираем 1-3 помещений по приоритету ROOM_WEIGHTS,
    но в случайном порядке.
    """
    k = rnd.choice([1, 2, 3])
    items = []
    weights = ROOM_WEIGHTS.copy()
    for _ in range(k):
        options = sorted(weights.keys(), key=lambda rr: -weights[rr])
        total = sum(weights[rr] for rr in options)
        x = rnd.uniform(0, total)
        cum = 0.0
        chosen = options[0]
        for rr in options:
            cum += weights[rr]
            if x <= cum:
                chosen = rr
                break
        items.append(chosen)
        weights.pop(chosen, None)
        if not weights:
            break
    rnd.shuffle(items)
    return items


