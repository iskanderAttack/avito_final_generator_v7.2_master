def ui_photo_logic(selected_model_ids):
    """
    Настройка логики выбора фото перед генерацией.
    Два режима:
      1) авто (приоритет помещений/ракурсов)
      2) ручной (ввод помещений и ракурсов по каждой линейке fam)
    """
    print("\n=== НАСТРОЙКА ФОТО ===")
    print("Режимы:\n  1) Авто (взвешенные помещения + приоритет ракурсов)\n  2) Ручной ввод по линейкам (musson/ciklon/triumf/tornado)")
    mode_raw = input("Выберите режим (1/2, Enter=1): ").strip() or "1"
    mode = "manual" if mode_raw == "2" else "auto"

    rng_raw = input("Сколько фото на объявление? (число или диапазон 7-10, Enter=10): ").strip()
    photo_min, photo_max = 7, 10
    if rng_raw:
        m = re.match(r"^\s*(\d+)\s*[-–]\s*(\d+)\s*$", rng_raw)
        if m:
            a, b = int(m.group(1)), int(m.group(2))
            low = min(a, b)
            high = max(a, b)
            photo_min, photo_max = max(1, low), max(1, high)
        elif rng_raw.isdigit():
            k = int(rng_raw)
            photo_min = max(1, k)
            photo_max = max(1, k)

    cl_on = input("Добавлять cl (без фона)? (Y/N, Enter=N): ").strip().lower() == "y"
    cl_pct = 0
    if cl_on:
        try:
            cl_pct = int(input("Макс доля cl (% от фото, 0..50, Enter=15): ").strip() or "15")
            cl_pct = max(0, min(50, cl_pct))
        except Exception:
            cl_pct = 15

    np_on = (input("Включать фото без префиксов? (Y/N, Enter=Y): ")
             .strip()
             .lower() or "y") == "y"
    np_pct = 10
    if np_on:
        try:
            np_pct = int(input("Вероятность кадра без префиксов (5..20%, Enter=10): ").strip() or "10")
            np_pct = max(5, min(20, np_pct))
        except Exception:
            np_pct = 10

    cfg = {
        "mode": mode,
        "photo_min": photo_min,
        "photo_max": photo_max,
        "cl_on": cl_on,
        "cl_pct": cl_pct,
        "np_on": np_on,
        "np_pct": np_pct,
    }

    if mode == "manual":
        # выясняем, какие fam вообще нужны
        fams = set(MODELS[mid]["fam"] for mid in selected_model_ids)
        fam_premises = {}
        fam_angles = {}
        print("\nРучной режим. Для каждой линейки укажите помещения и ракурсы.")
        print("Помещения из: lg, gb, skl, kr, osb")
        print("Ракурсы из: fr, r, l, b, mkr, cl")

        for fam in sorted(fams):
            p = input(f"[{fam}] помещения через запятую: ").strip()
            a = input(f"[{fam}] ракурсы через запятую: ").strip()
            fam_premises[fam] = [x.strip() for x in re.split(r"[\s,;]+", p) if x.strip()]
            fam_angles[fam] = [x.strip() for x in re.split(r"[\s,;]+", a) if x.strip()]

        cfg["fam_premises"] = fam_premises
        cfg["fam_angles"] = fam_angles

    return cfg


